"""Cloudflare Pages `_redirects` and `_headers` for the static site (DECISIONS D19).

Pages `_redirects` matches paths only, never the host, and its rules win over existing files.
Moving hosts (ondestaanocas.pages.dev -> pontonomada.pt) is therefore an account-level
Bulk Redirect, set up by hand once (docs/runbooks/brand-switch.md); it keeps the path and
query string, so every old URL lands on the same page of the new domain.

What the build generates:

- `_redirects` (301): `site.redirects` from config, pages whose path changed since they were
  first published (a deal or route slug renamed), and short `/promos/<id>` aliases. A rule
  never uses a path that is a page now, so it can't shadow a page or loop.
- `_headers`: `X-Robots-Tag: noindex` on retired hosts (`site.legacy_hosts` other than the
  `base_url` host) and on per-deployment `<hash>.<project>.pages.dev` URLs, so search engines
  only index `site.base_url` even before the Bulk Redirect exists.

Pure functions: the builder passes paths in and writes the text out.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field

from escapadinha.config import SiteConfig

MAX_STATIC_REDIRECTS = 2000   # Cloudflare Pages limit per _redirects file
HEADER = "# Generated by `escapadinha site build` (DECISIONS D19). Edit config.yaml, not this file.\n"


def variants(path: str) -> set[str]:
    """The request paths that reach the same page: '/a/' <-> '/a', '/' <-> '/index.html'."""
    bare = path.rstrip("/")
    if not bare:
        return {"/", "/index.html"}
    return {bare, f"{bare}/", f"{bare}/index.html"} if path.endswith("/") else {bare}


def _sources(path: str) -> list[str]:
    """Redirect sources for an old path: with and without the trailing slash."""
    bare = path.rstrip("/")
    return [bare, f"{bare}/"] if bare else []


@dataclass
class RedirectPlan:
    rules: list[tuple[str, str]] = field(default_factory=list)   # (source, target), 301
    skipped: list[str] = field(default_factory=list)              # why a wanted rule was left out
    warnings: list[str] = field(default_factory=list)             # e.g. close to the rule limit

    def text(self) -> str:
        return HEADER + "".join(f"{source} {target} 301\n" for source, target in self.rules)


def plan_redirects(pages: dict[str, str], history: dict[str, list[str]], *,
                   extra: dict[str, str], aliases: dict[str, str],
                   serves: Callable[[str], bool] | None = None,
                   limit: int | None = MAX_STATIC_REDIRECTS) -> RedirectPlan:
    """pages: stable key ('deal:42') -> current path; history: key -> paths published before.

    One rule per source (the first wanted wins). A rule whose target is itself a source points
    at the final target instead (no chains; a loop is left out). `serves`: whether a path is a
    page of the build; a rule to a path it doesn't serve is left out, before any limit counts.
    `limit`: rules beyond it are left out (reported); None keeps them all, for a caller that
    fails the build instead (`website.routing`)."""
    taken = set().union(*(variants(p) for p in pages.values())) if pages else set()
    plan = RedirectPlan()
    wanted: dict[str, str] = {}

    def add(source: str, target: str, *, explicit: bool = False) -> None:
        if source in wanted or source == target:
            return
        if source in taken:
            if explicit:
                plan.skipped.append(f"{source} -> {target}: {source} is a page of the site")
            return
        wanted[source] = target

    for source, target in extra.items():
        add(source, target, explicit=True)
    for key, old_paths in sorted(history.items()):
        current = pages.get(key)
        if current is None:
            continue   # page gone (e.g. route removed): an honest 404, not a redirect
        for old in old_paths:
            if old != current:
                for source in _sources(old):
                    add(source, current)
    for alias, target in aliases.items():
        for source in _sources(alias):
            add(source, target)
    for source, target in wanted.items():
        final, hops = target, {source}
        while final in wanted and final not in hops:     # collapse a chain to its end
            hops.add(final)
            final = wanted[final]
        if final in hops:
            plan.skipped.append(f"{source} -> {target}: a redirect loop")
        elif serves is not None and final.startswith("/") and not serves(final):
            plan.skipped.append(f"{source} -> {final}: {final} is not a page of the build")
        else:
            plan.rules.append((source, final))
    if limit is not None and len(plan.rules) > limit:
        plan.skipped += [f"{s} -> {t}: over the {limit}-rule limit" for s, t in plan.rules[limit:]]
        plan.rules = plan.rules[:limit]
    return plan


def update_history(history: dict[str, list[str]], pages: dict[str, str]) -> dict[str, list[str]]:
    """Remember every path a page has been published at (old links must keep working)."""
    merged = {key: list(paths) for key, paths in history.items()}
    for key, path in pages.items():
        if path not in merged.setdefault(key, []):
            merged[key].append(path)
    return merged


def headers_text(site: SiteConfig) -> str:
    """noindex for hosts that only exist to redirect, and for per-deployment preview URLs."""
    patterns = []
    for host in site.retired_hosts:
        patterns.append(f"https://{host}/*")
        if host.endswith(".pages.dev"):
            patterns.append(f"https://:version.{host}/*")
    patterns.append(f"https://:version.{site.cloudflare_project}.pages.dev/*")
    unique = list(dict.fromkeys(patterns))
    return HEADER + "\n".join(f"{p}\n  X-Robots-Tag: noindex\n" for p in unique)
